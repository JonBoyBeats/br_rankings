"""The Monday lock review, projections section (2026-11-23, the coordinator's request): every graded slate.

  0. the headline (2026-11-25, scripts/dk_proj_grade.py): ROTATION 10-25 and STARS 25+ by our projected DK points, per
     slate and pooled, the under-10 line secondary; the ownership crossover; the missed ceilings. The rule: a projection
     change counts only if it lowers ROTATION minutes MAE or STARS points MAE, held out by slate, without worsening the
     other band beyond noise, nor the banded proxy lenses (dk_eval.py projaudit: ownership agreement, salary gaps,
     minutes rank, top-5 hit for ROTATION and STARS) beyond theirs.
  1. the A2 lenses (scripts/dk_minutes_steep_study.py lenses: minutes MAE, points MAE, shape top-2 ours vs recent, the
     Vegas slope, salary gaps unexplained) per slate as the projection stood at lock, then pooled; DraftKings points MAE
     and bias by salary band and position, ours (fp_dk) and the page's gated projection (the gate's blend with DK's
     average, Questionable x the gate's factor)
  2. the misses log (analysis/cbb/dk/misses.csv) by reason tag
  3. the changes adopted since 11-16, re-checked on every slate held out where a number was fitted: the Questionable
     factor, the EvanMiya blend (fp_dk against fp_base_dk), the gate's weight per band, the zero-games factor (from
     sit_train.csv: the projection before the fix and the real points), the sit model's held-out Brier. The steeper
     minutes and the Out hand-off are re-run with their own scripts (dk_minutes_steep_study.py,
     dk_outhand_study.py) and quoted in the write-up.

  python3 scripts/dk_lock_review_proj.py
"""
import csv, glob, json, math, os, statistics as S, sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dk_minutes_steep_study as M     # noqa: E402

DK = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis", "cbb", "dk")
num = lambda v: float(v) if v not in ("", None) else None
GATE = json.load(open(os.path.join(DK, "gate.json")))
QF = GATE["questionable"]["factor"]
BANDS = [("under $4k", 0, 3999), ("$4-6k", 4000, 5999), ("$6k+", 6000, 99999)]


def slates():
    return [(os.path.basename(f)[:-4], list(csv.DictReader(open(f)))) for f in sorted(glob.glob(os.path.join(DK, "20??-??-??_*.csv")))
            if any(r.get("actual_dk") not in ("", None) for r in csv.DictReader(open(f)))]


def gated(r):
    """The page's projection (dk_sim.js gatedProj): ours and DK's average at the band's weight, x Q factor."""
    p, s = num(r.get("fp_dk")) or 0, num(r["salary"]) or 0
    b = next((b for b in GATE.get("bands", []) if b.get("open") and b["lo"] <= s <= b["hi"]), None)
    da = num(r.get("dk_avg"))
    if b and da:
        p = b["w"] * p + (1 - b["w"]) * da
    return p * QF if r.get("status") == "Questionable" else p


def pct(x):
    return "%.1f%%" % (100 * x)


def main():
    sl = slates()
    out = ["# Lock review 2026-11-23: projections (generated by `scripts/dk_lock_review_proj.py`)", "",
           "%d graded slates (%s). A thin sample: a slate is the unit; per-slate sign counts are the evidence, pooled numbers the size." % (len(sl), ", ".join(n for n, _ in sl)), ""]
    # 0. the headline (2026-11-25): ROTATION 10-25 and STARS 25+ by our projected points, the ownership crossover and
    # the missed ceilings (scripts/dk_proj_grade.py); the A2 lenses below stay as they were
    import dk_proj_grade as PG
    out += ["## Headline: the projection grade by band", ""] + PG.lines(md=True) + [""]
    # 1. lenses per slate
    out += ["## 1. The A2 lenses, as the projection stood at lock", "",
            "| Slate | Minutes MAE | Points MAE | Shape top-2 ours-recent | Vegas slope (ours) | Vegas slope (real) | Salary gaps (unexplained / all) |", "|---|---|---|---|---|---|---|"]
    PA = {(r["date"], r["draft_group"]): r for r in csv.DictReader(open(os.path.join(DK, "proj_audit.csv")))}
    L = []
    for n, rows in sl:
        x = M.lenses(rows, 0.0); L.append(x)
        pa = PA.get((n[:10], n[11:]), {})
        out.append("| %s | %.2f | %.2f | %s | %s | %s | %d / %d |" % (n, x["min_mae"], x["pts_mae"], "%+.3f" % x["shape_top2_vs_recent"] if x["shape_top2_vs_recent"] is not None else "–",
                                                                    "%.2f" % x["vegas_slope"] if x["vegas_slope"] is not None else "–", pa.get("vegas_slope_actual") or "–", x["unexplained"], x["gaps"]))
    m = lambda k: S.mean(v[k] for v in L if v[k] is not None)
    out += ["| **mean** | **%.2f** | **%.2f** | **%+.3f** | **%.2f** | | **%d / %d** |" % (m("min_mae"), m("pts_mae"), m("shape_top2_vs_recent"), m("vegas_slope"),
                                                                                 sum(v["unexplained"] for v in L), sum(v["gaps"] for v in L)), ""]
    # points MAE / bias by band and position
    out += ["### DraftKings points MAE and bias (actual - projected), players not Out", "",
            "| Group | n | MAE ours | bias ours | MAE page (gated) | bias page | slates where the page beats ours (MAE) |", "|---|---|---|---|---|---|---|"]
    groups = [(b[0], (lambda lo, hi: lambda r: lo <= (num(r["salary"]) or 0) <= hi)(b[1], b[2])) for b in BANDS] + \
             [("G", lambda r: (r.get("position") or "").startswith("G") and "F" not in (r.get("position") or "")),
              ("F", lambda r: (r.get("position") or "").startswith("F") or (r.get("position") or "") in ("C",)),
              ("G/F", lambda r: "G" in (r.get("position") or "") and "F" in (r.get("position") or "")), ("all", lambda r: True)]
    for g, f in groups:
        ea, eb, w, k = [], [], 0, 0
        for n, rows in sl:
            xs = [r for r in rows if r.get("status") != "Out" and f(r)]
            if not xs:
                continue
            a = [(num(r.get("actual_dk")) or 0) - (num(r.get("fp_dk")) or 0) for r in xs]
            b = [(num(r.get("actual_dk")) or 0) - gated(r) for r in xs]
            ea += a; eb += b; k += 1
            w += S.mean(abs(v) for v in b) < S.mean(abs(v) for v in a)
        if ea:
            out.append("| %s | %d | %.2f | %+.2f | %.2f | %+.2f | %d of %d |" % (g, len(ea), S.mean(abs(v) for v in ea), S.mean(ea), S.mean(abs(v) for v in eb), S.mean(eb), w, k))
    out.append("")
    # 2. misses by tag
    rows = list(csv.DictReader(open(os.path.join(DK, "misses.csv"))))
    tags = defaultdict(list)
    for r in rows:
        for t in (r.get("tags") or "").replace(";", ",").split(","):
            t = t.strip()
            if t:
                tags[(r["lens"], t)].append(abs(num(r["miss"]) or 0))
    known = {"teammate out", "Q status", "newcomer / few games", "back from injury / missed", "salary-value spot", "minutes role change"}
    out += ["## 2. The misses log by reason tag (%d rows, %d slates)" % (len(rows), len({(r['date'], r['draft_group']) for r in rows})), "",
            "Knowable before lock: a tag the card carries at lock (an Out teammate, a Q, few games, a salary-value spot, a role change seen in the last games); the rest (blowout, foul trouble, unexplained) show only after.", "",
            "| Lens | Tag | Misses | Mean size | Knowable pre-lock |", "|---|---|---|---|---|"]
    for (lens, t), v in sorted(tags.items(), key=lambda x: (x[0][0], -len(x[1]))):
        if len(v) >= 3:
            out.append("| %s | %s | %d | %.1f | %s |" % (lens, t, len(v), S.mean(v), "yes" if t in known else "no"))
    out.append("")
    # 3. adopted changes
    out += ["## 3. Changes adopted since 11-16, re-checked on every slate", ""]
    # Q factor, held out
    q = [(n, r) for n, rows in sl for r in rows if r.get("status") == "Questionable"]
    out += ["### Questionable factor (gate.json %.3f)" % QF, "",
            "%d Questionable player-nights on %d slates. Held out by slate: each slate's Q players at actual / projected over the other slates, against x1 and the current factor:" % (len(q), len({n for n, _ in q})), "",
            "| Slate | n | actual / projected | factor (others) | MAE x1 | MAE x factor |", "|---|---|---|---|---|---|"]
    better = cnt = 0
    for n, _ in sl:
        mine = [r for m_, r in q if m_ == n]
        oth = [r for m_, r in q if m_ != n]
        if not mine or not oth:
            continue
        f = sum(num(r["actual_dk"]) or 0 for r in oth) / max(1e-9, sum(num(r["fp_dk"]) or 0 for r in oth))
        a1 = S.mean(abs((num(r["actual_dk"]) or 0) - (num(r["fp_dk"]) or 0)) for r in mine)
        af = S.mean(abs((num(r["actual_dk"]) or 0) - f * (num(r["fp_dk"]) or 0)) for r in mine)
        ratio = sum(num(r["actual_dk"]) or 0 for r in mine) / max(1e-9, sum(num(r["fp_dk"]) or 0 for r in mine))
        out.append("| %s | %d | %.2f | %.3f | %.2f | %.2f |" % (n, len(mine), ratio, f, a1, af)); cnt += 1; better += af < a1
    out += ["", "The factor beats x1 on %d of %d slates with Q players." % (better, cnt), ""]
    # EvanMiya blend
    out += ["### EvanMiya blend (fp_dk with it, fp_base_dk without; players with both, not Out)", "", "| Slate | n | MAE with | MAE without |", "|---|---|---|---|"]
    wb = k = 0; aw = []; ab = []
    for n, rows in sl:
        xs = [r for r in rows if r.get("status") != "Out" and num(r.get("fp_base_dk")) is not None and num(r.get("fp_dk")) is not None]
        if not xs:
            continue
        a = [abs((num(r["actual_dk"]) or 0) - num(r["fp_dk"])) for r in xs]; b = [abs((num(r["actual_dk"]) or 0) - num(r["fp_base_dk"])) for r in xs]
        aw += a; ab += b; k += 1; wb += S.mean(a) < S.mean(b)
        out.append("| %s | %d | %.3f | %.3f |" % (n, len(xs), S.mean(a), S.mean(b)))
    out += ["| **pooled** | %d | **%.3f** | **%.3f** |" % (len(aw), S.mean(aw), S.mean(ab)), "", "With EvanMiya better on %d of %d slates." % (wb, k), ""]
    # gate weight per band
    out += ["### The gate's weight (w %s: ours x w + DK's average x (1 - w), players with a DK average)" % ", ".join("%s %.2f" % ("$%d-%d" % (b["lo"], b["hi"]), b["w"]) for b in GATE.get("bands", [])), "",
            "| Band | n | MAE ours | MAE DK avg | MAE at w 0.5 | best w (grid, pooled) | slates the 0.5 blend beats ours |", "|---|---|---|---|---|---|---|"]
    for name, lo, hi in BANDS:
        per = []
        for n, rows in sl:
            xs = [r for r in rows if r.get("status") != "Out" and lo <= (num(r["salary"]) or 0) <= hi and num(r.get("dk_avg"))]
            if xs:
                per.append([(num(r["actual_dk"]) or 0, num(r["fp_dk"]) or 0, num(r["dk_avg"])) for r in xs])
        allx = [x for p in per for x in p]
        if not allx:
            continue
        mae = lambda xs, w: S.mean(abs(a - (w * o + (1 - w) * d)) for a, o, d in xs)
        bw = min([i / 10 for i in range(11)], key=lambda w: mae(allx, w))
        out.append("| %s | %d | %.3f | %.3f | %.3f | %.1f | %d of %d |" % (name, len(allx), mae(allx, 1), mae(allx, 0), mae(allx, 0.5), bw, sum(1 for p in per if mae(p, 0.5) < mae(p, 1)), len(per)))
    out.append("")
    # zero-games factor
    st = list(csv.DictReader(open(os.path.join(DK, "sit_train.csv"))))
    z = [r for r in st if str(r.get("zero_gp")) == "1" and num(r.get("fp_raw")) and r.get("actual_dk") not in ("", None)]
    out += ["### Zero-games factor (sit_model.json %s; the group: 0 games, team 3+, not Out)" % json.load(open(os.path.join(DK, "sit_model.json"))).get("zero_gp_f"), "",
            "| Slate | n | played | actual / projected | factor (others) | MAE unscaled | MAE x factor |", "|---|---|---|---|---|---|---|"]
    names = sorted({(r["date"], r["draft_group"]) for r in z}); better = 0
    for s_ in names:
        mine = [r for r in z if (r["date"], r["draft_group"]) == s_]; oth = [r for r in z if (r["date"], r["draft_group"]) != s_]
        f = sum(num(r["actual_dk"]) for r in oth) / sum(num(r["fp_raw"]) for r in oth)
        a0 = S.mean(abs(num(r["actual_dk"]) - num(r["fp_raw"])) for r in mine); af = S.mean(abs(num(r["actual_dk"]) - f * num(r["fp_raw"])) for r in mine)
        better += af < a0
        out.append("| %s_%s | %d | %d | %.3f | %.3f | %.2f | %.2f |" % (s_[0], s_[1], len(mine), sum(int(r["played"]) for r in mine),
                                                                     sum(num(r["actual_dk"]) for r in mine) / sum(num(r["fp_raw"]) for r in mine), f, a0, af))
    out += ["", "The held-out factor beats no cut on %d of %d slates (%d player-slates, %d played)." % (better, len(names), len(z), sum(int(r["played"]) for r in z)), ""]
    # sit model
    sm = json.load(open(os.path.join(DK, "sit_model.json")))
    lg = list(csv.DictReader(open(os.path.join(DK, "sit_log.csv"))))
    out += ["### Sit model and flag", "", "Fitted on %d players, %d slates; held-out Brier %s (model) vs %s (the current implied chance) over %d players. Flags logged at lock: %d." % (
        sm["n"], len(sm["slates"]), sm["heldout_brier"]["model"], sm["heldout_brier"]["current"], sm["heldout_brier"]["n"], len(lg)), ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
